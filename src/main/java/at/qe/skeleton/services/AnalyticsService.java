    /**
     * Asserts that the current user may read data from this room.
     *
     * <ul>
     *   <li><b>BUILDING_ADMIN</b> – always allowed.</li>
     *   <li><b>DEPARTMENT_LEAD</b> – room must belong to their department (office or common area).</li>
     *   <li><b>EMPLOYEE</b> – only their own assigned office, or common areas of their department.</li>
     * </ul>
     *
     * @throws AccessDeniedException when access is not permitted
     */
    private void assertRoomReadAccess(Userx user, Room room) {
        if (hasRole(user, UserxRole.BUILDING_ADMIN)) return;

        EmployeeProfile profile = employeeProfileService.getMyProfile().orElse(null);

        if (hasRole(user, UserxRole.DEPARTMENT_LEAD)) {
            if (room.getDepartment() == null || !isLeaderOf(user, room.getDepartment())) {
                throw new AccessDeniedException("Room does not belong to your department.");
            }
            return;
        }

        if (hasRole(user, UserxRole.EMPLOYEE)) {
            if (profile == null) {
                throw new AccessDeniedException("No employee profile found.");
            }

            Department employeeDept = profile.getDepartment();
            boolean isOwnRoom = profile.getRoom() != null && profile.getRoom().getId().equals(room.getId());
            boolean isCommonArea =
                    room.getRoomType() == RoomType.COMMON_AREAS
                            && room.getDepartment() != null
                            && employeeDept != null
                            && room.getDepartment().getId().equals(employeeDept.getId());

            if (!isOwnRoom && !isCommonArea) {
                throw new AccessDeniedException("You may only view your own room or common areas of your department.");
            }
            return;
        }

        throw new AccessDeniedException("Insufficient privileges to access room data.");
    }

    /**
     * Enforces the minimum-occupancy / privacy-mode guard for EMPLOYEE access to office rooms.
     *
     * <p>Common areas bypass this check entirely. DEPARTMENT_LEAD and BUILDING_ADMIN are also
     * exempt — the Department Lead sees reduced granularity for occupied offices instead
     * (handled in {@link #getRoomTrend}).</p>
     *
     * @throws AccessDeniedException when privacy mode is active (minimum occupancy not met)
     */
    private void assertOccupancyIfRequired(Userx user, Room room) {
        if (!hasRole(user, UserxRole.EMPLOYEE)) return;
        if (room.getRoomType() == RoomType.COMMON_AREAS) return;

        if (Boolean.TRUE.equals(room.getPrivacyMode())) {
            throw new AccessDeniedException("Room climate data is not available: minimum occupancy requirement not met.");
        }
    }

    private boolean hasRole(Userx user, UserxRole role) {
        return user.getRoles() != null && user.getRoles().contains(role);
    }

    private boolean isLeaderOf(Userx user, Department department) {
        if (user == null || department == null) return false;

        Userx leader = department.getDepartmentLeader();
        if (leader == null) return false;

        return Objects.equals(leader.getId(), user.getId());
    }

    private MetricSummaryDTO buildMetricSummary(List<Measurement> all, Metric metric) {
        List<Float> values = all.stream()
                .filter(m -> m.getMetric() == metric)
                .sorted(Comparator.comparing(Measurement::getTimestamp))
                .map(Measurement::getMeasurement)
                .toList();

        if (values.isEmpty()) {
            return new MetricSummaryDTO(null, null, null, null, 0L);
        }

        double avg = round2(values.stream().mapToDouble(Float::doubleValue).average().orElse(0));
        double min = round2(values.stream().mapToDouble(Float::doubleValue).min().orElse(0));
        double max = round2(values.stream().mapToDouble(Float::doubleValue).max().orElse(0));
        double latest = round2(values.getLast());

        return new MetricSummaryDTO(latest, avg, min, max, (long) values.size());
    }

    /**
     * Forced reduced bucket for DEPARTMENT_LEAD viewing occupied office rooms.
     * Minimum granularity is daily averages regardless of window length, as required
     * by the privacy specification (§1.5.3 Abteilungsleitung).
     *
     * <p>Bucket mapping:</p>
     * <ul>
     *   <li>≤ 30 days → {@code 1d} (daily averages)</li>
     *   <li>&gt; 30 days → {@code 1w} (weekly averages)</li>
     * </ul>
     */
    private String forcedReducedBucket(LocalDateTime from, LocalDateTime to) {
        long hours = ChronoUnit.HOURS.between(from, to);
        if (hours <= 720) return "1d";
        return "1w";
    }

    /**
     * Automatic bucket resolution based on window length.
     *
     * <ul>
     *   <li>≤ 7 d  → {@code raw} </li>
     *   <li>≤ 90 d → {@code 1h}  </li>
     *   <li>≤ 1 y  → {@code 6h}  </li>
     *   <li>&gt; 1 y → {@code 1d}</li>
     * </ul>
     */
    private String resolveBucketSize(LocalDateTime from, LocalDateTime to) {
        long hours = ChronoUnit.HOURS.between(from, to);
        if (hours <= 168)  return "raw";
        if (hours <= 2160) return "1h";
        if (hours <= 8760) return "6h";
        return "1d";
    }

    /**
     * Builds a room-fair time-series from per-room measurement maps.
     *
     * <p>Algorithm:</p>
     * <ol>
     *   <li>Bucket each room's measurements independently into the same time grid.</li>
     *   <li>For every bucket timestamp, average the per-room bucket averages
     *       (rooms with no data in a bucket are excluded, not counted as zero).</li>
     * </ol>
     *
     * <p>This ensures that rooms with higher sensor frequency or longer uptime do not
     * dominate the cross-room aggregate — each room contributes equally per bucket.</p>
     *
     * @param byRoom     measurements per room ID
     * @param from       effective window start
     * @param to         effective window end
     * @param bucketSize resolved bucket size string (e.g. {@code "1h"}, {@code "1d"})
     * @return room-fair trend points sorted by timestamp
     */
    private List<TrendPointDTO> toRoomFairPoints(Map<Long, List<Measurement>> byRoom,
                                                 LocalDateTime from,
                                                 LocalDateTime to,
                                                 String bucketSize) {
        if (byRoom.isEmpty()) return Collections.emptyList();

        // For "raw" bucket in a multi room context we still bucket by 1m slots
        // so that cross-room averaging is meaningful, raw is only meaningful for single rooms.
        String effectiveBucket = "raw".equals(bucketSize) ? "raw" : bucketSize;

        if ("raw".equals(effectiveBucket)) {
            // Flat merge and sort: only reached for single room callers; multi-room callers
            // always get a non raw bucket from resolveBucketSize via getDepartmentTrend /
            // getCompanyTrend (those default to >= 7-day windows).
            List<Measurement> all = byRoom.values().stream()
                    .flatMap(Collection::stream)
                    .sorted(Comparator.comparing(Measurement::getTimestamp))
                    .toList();
            return all.stream()
                    .map(m -> new TrendPointDTO(m.getTimestamp(), round2(m.getMeasurement())))
                    .toList();
        }

        long bucketMinutes = switch (effectiveBucket) {
            case "1d" -> 1440L;
            case "1w" -> 10080L;
            case "6h" -> 360L;
            default   -> 60L;
        };

        // Bucket each room independently: Map<roomId, Map<bucketKey, List<value>>>
        Map<Long, Map<LocalDateTime, Double>> roomBucketAverages = new HashMap<>();

        for (Map.Entry<Long, List<Measurement>> entry : byRoom.entrySet()) {
            Map<LocalDateTime, List<Float>> buckets = new TreeMap<>();

            for (Measurement m : entry.getValue()) {
                LocalDateTime ts = m.getTimestamp();

                if (ts.isBefore(from) || ts.isAfter(to)) continue;

                long idx = ChronoUnit.MINUTES.between(from, ts) / bucketMinutes;
                LocalDateTime key = from.plusMinutes(idx * bucketMinutes);
                buckets.computeIfAbsent(key, k -> new ArrayList<>()).add(m.getMeasurement());
            }
            // Collapse each bucket to its average for this room
            Map<LocalDateTime, Double> roomAvg = new TreeMap<>();
            buckets.forEach((k, vals) -> roomAvg.put(k,
                    vals.stream().mapToDouble(Float::doubleValue).average().orElse(0.0)));
            roomBucketAverages.put(entry.getKey(), roomAvg);
        }

        // Collect all unique bucket timestamps across all rooms
        Set<LocalDateTime> allKeys = roomBucketAverages.values().stream()
                .flatMap(m -> m.keySet().stream())
                .collect(Collectors.toCollection(TreeSet::new));

        // For each timestamp, average the room averages (only rooms that have data)
        return allKeys.stream()
                .map(ts -> {
                    double crossRoomAvg = roomBucketAverages.values().stream()
                            .map(roomAvg -> roomAvg.get(ts))
                            .filter(Objects::nonNull)
                            .mapToDouble(Double::doubleValue)
                            .average()
                            .orElse(0.0);
                    return new TrendPointDTO(ts, round2(crossRoomAvg));
                })
                .toList();
    }

    private List<TrendPointDTO> toPoints(List<Measurement> measurements,
                                         LocalDateTime from, LocalDateTime to,
                                         String bucketSize) {

        if (measurements.isEmpty()) return Collections.emptyList();

        if ("raw".equals(bucketSize)) {
            return measurements.stream()
                    .sorted(Comparator.comparing(Measurement::getTimestamp))
                    .map(m ->
                            new TrendPointDTO(
                                    m.getTimestamp(),
                                    round2(m.getMeasurement()))
                    )
                    .toList();
        }
        return bucketize(measurements, from, to, bucketSize);
    }

    private List<TrendPointDTO> bucketize(List<Measurement> measurements,
                                          LocalDateTime from, LocalDateTime to,
                                          String bucketSize) {
        long bucketMinutes = switch (bucketSize) {
            case "1d" -> 1440L;
            case "1w" -> 10080L;
            case "6h" -> 360L;
            default   -> 60L;
        };

        Map<LocalDateTime, List<Float>> buckets = new TreeMap<>();
        for (Measurement m : measurements) {
            LocalDateTime ts = m.getTimestamp();
            if (ts.isBefore(from) || ts.isAfter(to)) continue;

            long minutesSinceFrom = ChronoUnit.MINUTES.between(from, ts);
            long bucketIndex = minutesSinceFrom / bucketMinutes;
            LocalDateTime key = from.plusMinutes(bucketIndex * bucketMinutes);

            buckets.computeIfAbsent(key, k -> new ArrayList<>()).add(m.getMeasurement());
        }

        return buckets.entrySet().stream()
                .map(e -> new TrendPointDTO(
                        e.getKey(),
                        round2(e.getValue().stream()
                                .mapToDouble(Float::doubleValue)
                                .average()
                                .orElse(0))))
                .toList();
    }

    /**
     * Computes per-metric averages across a list of rooms using a two-level mean:
     * first the average per room, then the average of those room averages.
     *
     * <p>This prevents rooms with higher sensor frequency or longer uptime from dominating
     * the result (flat-merge bias). Each room contributes exactly one value per metric,
     * regardless of how many measurements it produced in the window.</p>
     *
     * <p>Rooms that have no measurements for a given metric in the window are excluded
     * from that metric's average (they contribute no signal, not a zero).</p>
     */
    private Map<Metric, Double> computeAvgMetricsForRooms(List<Room> rooms,
                                                          LocalDateTime from,
                                                          LocalDateTime to) {

        if (rooms.isEmpty()) return Collections.emptyMap();

        LocalDateTime effectiveTo = to != null ? to : LocalDateTime.now();
        LocalDateTime effectiveFrom = from != null ? from : effectiveTo.minusHours(24);

        // Fetch measurements per room up front
        Map<Long, List<Measurement>> byRoom = new HashMap<>();
        for (Room r : rooms) {
            byRoom.put(r.getId(),
                    measurementService.getFiltered(r.getId(), null, effectiveFrom, effectiveTo));
        }

        return Arrays.stream(Metric.values())
                .collect(Collectors.toMap(
                        metric -> metric,
                        metric -> {
                            // Compute the average for this metric inside each room
                            List<Double> roomAverages = byRoom.values().stream()
                                    .map(measurements -> measurements.stream()
                                            .filter(m -> m.getMetric() == metric)
                                            .mapToDouble(Measurement::getMeasurement)
                                            .average())
                                    .filter(OptionalDouble::isPresent)
                                    .map(OptionalDouble::getAsDouble)
                                    .toList();

                            // Average the per-room averages (room-fair mean)
                            return round2(roomAverages.stream()
                                    .mapToDouble(Double::doubleValue)
                                    .average()
                                    .orElse(0.0));
                        }
                ));
    }

    /**
     * Computes the "momentane Messwerte" (current readings) for a list of rooms.
     *
     * <p>For each room, the most recent measurement per metric is taken. The values from
     * all rooms are then averaged using a room-fair mean (each room contributes equally,
     * regardless of sensor count). Rooms with no measurements for a metric are excluded.</p>
     *
     * <p>This is separate from the windowed average returned by
     * {@link #computeAvgMetricsForRooms} and reflects the current state of conditions,
     * as required by §1.5.3 ("momentane Messwerte") for department/company views.</p>
     */
    private Map<Metric, Double> computeLatestMetricsForRooms(List<Room> rooms) {
        if (rooms.isEmpty()) return Collections.emptyMap();

        return Arrays.stream(Metric.values())
                .collect(Collectors.toMap(
                        metric -> metric,
                        metric -> {

                            List<Double> latestPerRoom = rooms.stream()
                                    .map(r -> measurementService
                                            .getFiltered(r.getId(), metric,
                                                    LocalDateTime.now().minusHours(12),
                                                    LocalDateTime.now())
                                            .stream()
                                            .max(Comparator.comparing(Measurement::getTimestamp))
                                            .map(m -> (double) m.getMeasurement()))
                                    .filter(Optional::isPresent)
                                    .map(Optional::get)
                                    .toList();

                            return round2(latestPerRoom.stream()
                                    .mapToDouble(Double::doubleValue)
                                    .average()
                                    .orElse(0.0));
                        }
                ));
    }

    /**
     * Builds a {@link ViolationSummaryDTO} from a raw list of violations.
     *
     * <p>When {@code anonymize} is {@code true} (MANAGEMENT role) the {@code byRoom} list is
     * intentionally left empty so that violations cannot be traced back to individual rooms.</p>
     */
    private ViolationSummaryDTO buildViolationSummary(List<ThresholdViolation> violations,
                                                      List<Long> roomIds,
                                                      List<Room> rooms,
                                                      boolean anonymize) {
        int total = violations.size();
        int active = (int) violations.stream()
                .filter(v -> v.getViolationStatus() == ViolationStatus.ACTIVE).count();
        int resolved = (int) violations.stream()
                .filter(v -> v.getViolationStatus() == ViolationStatus.RESOLVED).count();

        List<ViolationBreakdownDTO> byMetric = Arrays.stream(Metric.values())
                .map(metric -> new ViolationBreakdownDTO(
                        metric.name(),
                        (int) violations.stream()
                                .filter(v -> v.getMetric() == metric).count()))
                .filter(dto -> dto.count() > 0)
                .toList();

        List<ViolationBreakdownDTO> byRoom = anonymize
                ? Collections.emptyList()
                : buildByRoomBreakdown(violations, roomIds, rooms);

        return new ViolationSummaryDTO(total, active, resolved, byMetric, byRoom);
    }

    private List<ViolationBreakdownDTO> buildByRoomBreakdown(List<ThresholdViolation> violations,
                                                             List<Long> roomIds,
                                                             List<Room> rooms) {

        Map<Long, String> roomNameById = rooms
                .stream()
                .collect(Collectors.toMap(Room::getId, Room::getName));

        return roomIds.stream()
                .map(rid -> new ViolationBreakdownDTO(
                        roomNameById.getOrDefault(rid, "Room " + rid),
                        (int) violations.stream()
                                .filter(v -> v.getRoom() != null
                                        && rid.equals(v.getRoom().getId()))
                                .count()))
                .filter(dto -> dto.count() > 0)
                .toList();
    }

    private void validateRange(LocalDateTime from, LocalDateTime to) {
        if (from != null && to != null && from.isAfter(to)) {
            throw new BadRequestException("Invalid date range: 'from' must be before 'to'.");
        }
    }

    private double round2(double value) {
        return Math.round(value * 100.0) / 100.0;
    }
