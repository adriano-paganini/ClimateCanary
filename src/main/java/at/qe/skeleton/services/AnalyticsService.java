    /**
     * Returns a statistical summary (latest, avg, min, max, count) for every metric
     * measured in the requested room over the given time window.
     *
     * <p><b>Access rules:</b></p>
     * <ul>
     *   <li><b>EMPLOYEE</b> – own office only (privacy-mode / minimum-occupancy guard applies);
     *       common areas of their department are always accessible.</li>
     *   <li><b>DEPARTMENT_LEAD</b> – any room that belongs to their department.</li>
     *   <li><b>BUILDING_ADMIN</b> – any room, unrestricted.</li>
     * </ul>
     *
     * <p>When {@code from} / {@code to} are omitted the service defaults to the last 24 hours.</p>
     *
     * @param roomId the ID of the room whose summary is requested
     * @param from   optional window start (inclusive); defaults to {@code to – 24 h}
     * @param to     optional window end (inclusive); defaults to now
     * @return {@link RoomSummaryDTO} containing per-metric statistics
     * @throws AccessDeniedException if the caller lacks read access to the room
     * @throws ConflictException     if {@code from} is after {@code to}
     */
    @PreAuthorize("hasAnyAuthority('EMPLOYEE','DEPARTMENT_LEAD','BUILDING_ADMIN')")
    public RoomSummaryDTO getRoomSummary(Long roomId, LocalDateTime from, LocalDateTime to) {
        Room room = roomService.getById(roomId);
        Userx currentUser = authenticatedUserService.getAuthenticatedUser();

        assertRoomReadAccess(currentUser, room);
        assertOccupancyIfRequired(currentUser, room);

        LocalDateTime effectiveTo = to != null ? to : LocalDateTime.now();
        LocalDateTime effectiveFrom = from != null ? from : effectiveTo.minusHours(24);
        validateRange(effectiveFrom, effectiveTo);

        List<Measurement> measurements = measurementService.getFiltered(roomId, null, effectiveFrom, effectiveTo);

        Map<Metric, MetricSummaryDTO> metricStats = Arrays.stream(Metric.values())
                .collect(Collectors.toMap(m -> m, m -> buildMetricSummary(measurements, m)));

        log.debug("Generated room summary for roomId={}, userId={}", roomId, currentUser.getId());
        return new RoomSummaryDTO(roomId, room.getName(), LocalDateTime.now(), metricStats);
    }

    /**
     * Returns a time-series trend for a single metric in the requested room.
     *
     * <p><b>Granularity rules:</b></p>
     * <ul>
     *   <li><b>EMPLOYEE / BUILDING_ADMIN</b> – automatic bucket selection based on window length
     *       (raw ≤ 7 d, 1 h ≤ 90 d, 6 h ≤ 1 y, 1 d otherwise).</li>
     *   <li><b>DEPARTMENT_LEAD viewing an office room above minimum occupancy</b> – forced reduced
     *       granularity (minimum daily averages) regardless of window length, as required by the
     *       privacy specification.</li>
     *   <li><b>DEPARTMENT_LEAD viewing a common area</b> – full automatic granularity.</li>
     * </ul>
     *
     * <p>When {@code from} / {@code to} are omitted the service defaults to the last 24 hours.</p>
     *
     * @param roomId the ID of the room
     * @param metric the climate metric to retrieve (e.g. TEMPERATURE, CO2)
     * @param from   optional window start; defaults to {@code to – 24 h}
     * @param to     optional window end; defaults to now
     * @return {@link RoomTrendDTO} containing the resolved bucket size and data points
     * @throws AccessDeniedException if the caller lacks read access to the room
     * @throws ConflictException     if {@code from} is after {@code to}
     */
    @PreAuthorize("hasAnyAuthority('EMPLOYEE','DEPARTMENT_LEAD','BUILDING_ADMIN')")
    public RoomTrendDTO getRoomTrend(Long roomId, Metric metric, LocalDateTime from, LocalDateTime to) {
        Room room = roomService.getById(roomId);
        Userx currentUser = authenticatedUserService.getAuthenticatedUser();

        assertRoomReadAccess(currentUser, room);
        assertOccupancyIfRequired(currentUser, room);

        LocalDateTime effectiveTo = to != null ? to : LocalDateTime.now();
        LocalDateTime effectiveFrom = from != null ? from : effectiveTo.minusHours(24);
        validateRange(effectiveFrom, effectiveTo);

        List<Measurement> measurements = measurementService.getFiltered(
                roomId, metric, effectiveFrom, effectiveTo);

        /*
         * DEPARTMENT_LEAD + office room: apply forced reduced granularity only when the room
         * is above minimum occupancy (privacy mode OFF). If privacy mode is ON the room would
         * have already been blocked by assertOccupancyIfRequired for EMPLOYEEs; DEPARTMENT_LEAD
         * is exempt from the hard block but still sees reduced granularity for occupied offices.
         *
         * Common areas are always shown at full granularity for all roles.
         */
        boolean forceReduced = hasRole(currentUser, UserxRole.DEPARTMENT_LEAD)
                && room.getRoomType() == RoomType.OFFICE
                && !Boolean.TRUE.equals(room.getPrivacyMode());

        String bucketSize = forceReduced
                ? forcedReducedBucket(effectiveFrom, effectiveTo)
                : resolveBucketSize(effectiveFrom, effectiveTo);

        List<TrendPointDTO> points = toPoints(measurements, effectiveFrom, effectiveTo, bucketSize);

        log.debug("Generated room trend: roomId={}, metric={}, bucketSize={}, forceReduced={}",
                roomId, metric, bucketSize, forceReduced);
        return new RoomTrendDTO(roomId, metric, bucketSize, forceReduced, points);
    }

    /**
     * Returns a violation summary for a single room broken down by metric.
     *
     * <p><b>Access rules:</b></p>
     * <ul>
     *   <li><b>EMPLOYEE</b> – own office only (occupancy guard applies); common areas of their department.</li>
     *   <li><b>DEPARTMENT_LEAD</b> – any room in their department.</li>
     *   <li><b>BUILDING_ADMIN</b> – any room.</li>
     * </ul>
     *
     * @throws AccessDeniedException if the caller lacks read access to the room
     */
    @PreAuthorize("hasAnyAuthority('EMPLOYEE','DEPARTMENT_LEAD','BUILDING_ADMIN')")
    public RoomViolationSummaryDTO getRoomViolationSummary(Long roomId) {
        Room room = roomService.getById(roomId);
        Userx currentUser = authenticatedUserService.getAuthenticatedUser();

        assertRoomReadAccess(currentUser, room);
        assertOccupancyIfRequired(currentUser, room);

        List<ThresholdViolation> violations = thresholdViolationService.findAll(null, roomId, null);

        int total    = violations.size();
        int active   = (int) violations.stream()
                .filter(v -> v.getViolationStatus() == ViolationStatus.ACTIVE).count();
        int resolved = (int) violations.stream()
                .filter(v -> v.getViolationStatus() == ViolationStatus.RESOLVED).count();

        List<ViolationBreakdownDTO> byMetric = Arrays.stream(Metric.values())
                .map(metric -> new ViolationBreakdownDTO(
                        metric.name(),
                        (int) violations.stream()
                                .filter(v -> v.getMetric() == metric).count()))
                .filter(dto -> dto.count() > 0)
                .toList();

        log.debug("Generated room violation summary: roomId={}, total={}, active={}", roomId, total, active);
        return new RoomViolationSummaryDTO(roomId, room.getName(), total, active, resolved, byMetric);
    }

    /**
     * Returns an aggregated summary for an entire department: active violation count and
     * average metric values across all active rooms in the requested time window.
     *
     * <p><b>Access rules:</b></p>
     * <ul>
     *   <li><b>DEPARTMENT_LEAD</b> – their own department only.</li>
     *   <li><b>MANAGEMENT / BUILDING_ADMIN</b> – any department.</li>
     * </ul>
     *
     * @param departmentId the ID of the department
     * @param from         optional window start; defaults to {@code to – 24 h}
     * @param to           optional window end; defaults to now
     * @return {@link DepartmentAnalyticsDTO} with room count, active violations, windowed avg metrics,
     *         and current (latest-per-room) metric snapshot
     * @throws AccessDeniedException if a DEPARTMENT_LEAD requests another department
     */
    @PreAuthorize("hasAnyAuthority('DEPARTMENT_LEAD','MANAGEMENT','BUILDING_ADMIN')")
    public DepartmentAnalyticsDTO getDepartmentSummary(Long departmentId,
                                                       LocalDateTime from, LocalDateTime to) {
        Department department = departmentService.getDepartmentById(departmentId);
        Userx currentUser = authenticatedUserService.getAuthenticatedUser();

        if (hasRole(currentUser, UserxRole.DEPARTMENT_LEAD) && !isLeaderOf(currentUser, department)) {
            throw new AccessDeniedException("You may only view your own department.");
        }

        List<Room> rooms = department.getRooms().stream()
                .filter(Room::isActive)
                .toList();

        int activeViolations = rooms.stream()
                .mapToInt(r -> thresholdViolationService
                        .findAll(ViolationStatus.ACTIVE, r.getId(), null).size()).sum();

        Map<Metric, Double> avgMetrics = computeAvgMetricsForRooms(rooms, from, to);

        // "momentane Messwerte": latest reading per room averaged across rooms
        // This gives a snapshot of current conditions distinct from the windowed average
        Map<Metric, Double> currentMetrics = computeLatestMetricsForRooms(rooms);

        log.debug("Generated department summary for departmentId={}", departmentId);
        return new DepartmentAnalyticsDTO(departmentId, department.getName(), rooms.size(), activeViolations,
                avgMetrics, currentMetrics);
    }

