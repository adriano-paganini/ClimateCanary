    /**
     * Returns a company-wide dashboard aggregating employee count, total active rooms,
     * total active violations, and per-department breakdowns with average metric values.
     *
     * <p>Intended as the top-level entry point for MANAGEMENT trend monitoring and
     * BUILDING_ADMIN operational oversight.</p>
     *
     * <p>Default window when omitted: last 7 days.</p>
     *
     * @param from optional window start for metric averages; defaults to {@code to – 7 d}
     * @param to   optional window end; defaults to now
     * @return {@link CompanyDashboardDTO} with aggregated company-wide data
     * @throws ConflictException if {@code from} is after {@code to}
     */
    @PreAuthorize("hasAnyAuthority('MANAGEMENT','BUILDING_ADMIN')")
    public CompanyDashboardDTO getCompanyDashboard(LocalDateTime from, LocalDateTime to) {
        List<Department> departments = departmentService.getAll();

        LocalDateTime effectiveTo = to != null ? to : LocalDateTime.now();
        LocalDateTime effectiveFrom = from != null ? from : effectiveTo.minusDays(7);
        validateRange(effectiveFrom, effectiveTo);

        int totalEmployees = employeeProfileService.getAll(null, null).size();
        int totalRooms = 0;
        int activeViolations = 0;
        List<DepartmentDashboardDTO> departmentDTOs = new ArrayList<>();

        for (Department dept : departments) {
            List<Room> rooms = dept.getRooms().stream()
                    .filter(Room::isActive)
                    .toList();
            totalRooms += rooms.size();

            int deptActiveViolations = rooms.stream()
                    .mapToInt(r -> thresholdViolationService
                            .findAll(ViolationStatus.ACTIVE, r.getId(), null).size())
                    .sum();
            activeViolations += deptActiveViolations;

            Map<Metric, Double> avgMetrics = computeAvgMetricsForRooms(rooms, effectiveFrom, effectiveTo);
            Map<Metric, Double> currentMetrics = computeLatestMetricsForRooms(rooms);

            departmentDTOs.add(new DepartmentDashboardDTO(
                    dept.getId(), dept.getName(), deptActiveViolations, avgMetrics, currentMetrics));
        }

        log.debug("Generated company dashboard: departments={}, totalRooms={}, activeViolations={}",
                departments.size(), totalRooms, activeViolations);
        return new CompanyDashboardDTO(LocalDateTime.now(), totalRooms, totalEmployees, activeViolations, departmentDTOs);
    }

